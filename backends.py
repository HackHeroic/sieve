"""
Two compute backends, one set of permutations.

The rule that makes this safe
-----------------------------
Both backends consume the SAME index matrix, generated by
`core.block_permutation`.  A given seed therefore produces bit-identical
results on a laptop and on a GPU, and `--device` is a speed knob rather than a
different experiment.

That is not how the GPU module originally worked.  `gpu_full.block_idx_gpu`
generates its own block orders, vectorised, but it ignores the `strata`
argument and pins the ragged tail block in place.  The CPU path stratifies by
calendar month.  Left alone, the two devices would have been sampling from
different nulls and quietly reporting different numbers for the same seed.

Sharing the CPU generator costs 4.3 ms per batch of 32, measured, against a
5.6 ms counting kernel.  Worth it.

What each device actually does
------------------------------
The GPU does the counting, which is where the 387 MB of rule bitsets is
streamed.  The p-value scan stays on the CPU on both paths: see the note in
`gpu_full.py` for why the GPU min-p kernel was deleted rather than kept.
"""
from __future__ import annotations

import numpy as np

from core import pack, popcount

MAX_GPU_BATCH = 32          # popcount_batch declares int acc[32]


class CPUBackend:
    """
    numpy bitsets.  NOT numba: `core.popcount` is `np.bitwise_count(...).sum()`,
    which is single-threaded and unfused.  It materialises a 387 MB uint64
    temporary for the AND and a 48 MB uint8 temporary for the count, so it moves
    about 1.26 GB per permutation to do 0.39 GB of useful work.

    Measured on this machine: 57.2 ms/perm = 6.8 GB/s of useful traffic.  Apple
    Silicon sustains 100-400 GB/s, so this baseline is bound by numpy's lack of
    fusion, NOT by memory bandwidth.  Any speedup quoted against it is a speedup
    against unfused numpy, and should be described that way.
    """
    name = "cpu"
    label = "CPU, numpy bitsets"
    batch = 1

    def __init__(self, rules):
        self.rules = np.ascontiguousarray(rules, dtype=np.uint64)
        self.R, self.W = self.rules.shape

    def counts(self, y, idx_batch):
        out = np.empty((len(idx_batch), self.R), dtype=np.int64)
        for k, idx in enumerate(idx_batch):
            out[k] = popcount(self.rules & pack(y[idx])[None, :])
        return out

    def close(self):
        pass


class GPUBackend:
    name = "gpu"
    batch = MAX_GPU_BATCH

    def __init__(self, rules, kernel="unrolled"):
        import cupy as cp
        from gpu_full import gather_pack
        if kernel == "unrolled":
            from gpu_kernel_u import counts_batch_u as counts_batch
        elif kernel == "warp":
            from gpu_kernel_warp import counts_batch_warp as counts_batch
        elif kernel == "smem":
            from gpu_kernel_smem import counts_batch_smem as counts_batch
        else:
            from gpu_kernel import counts_batch
        self._cp, self._counts, self._pack = cp, counts_batch, gather_pack
        self.kernel = kernel
        r = np.ascontiguousarray(rules, dtype=np.uint64)
        self.R, self.W = r.shape
        self.rules_gpu = cp.asarray(r)
        props = cp.cuda.runtime.getDeviceProperties(cp.cuda.Device().id)
        self.label = f"GPU, {props['name'].decode()} ({kernel}-per-rule)"

    def counts(self, y, idx_batch):
        cp = self._cp
        B = len(idx_batch)
        if B > MAX_GPU_BATCH:
            raise ValueError(f"batch {B} exceeds kernel limit {MAX_GPU_BATCH}")
        n = y.size
        yg = cp.asarray(np.ascontiguousarray(y, dtype=np.uint8))
        ig = cp.asarray(np.ascontiguousarray(np.asarray(idx_batch, dtype=np.int32)))
        ys = self._pack(yg, ig, n, self.W, B)
        c = self._counts(self.rules_gpu, ys, B, self.R, self.W)
        return cp.asnumpy(c).astype(np.int64)

    def close(self):
        del self.rules_gpu
        self._cp.get_default_memory_pool().free_all_blocks()


def gpu_available():
    """True only if cupy imports AND a device actually answers."""
    try:
        import cupy as cp
        return cp.cuda.runtime.getDeviceCount() > 0
    except Exception:
        return False


def make(device, rules, kernel="unrolled"):
    """
    device is 'cpu', 'gpu', or 'auto'.

    kernel selects the GPU counting kernel.  All four produce bit-identical
    output (`kernel_ab.py` asserts it); measured on an L4, 66,844 rules, B = 32:

        thread      one thread per rule, the original   8.691 ms   44.5 GB/s  19.0% of roof
        warp        one warp per rule, coalesced reads  5.253 ms   73.7 GB/s  31.4%
        smem        warp + ys staged in shared memory   5.616 ms   68.9 GB/s  29.3%
        unrolled    warp + compile-time B, unrolled     3.430 ms  112.9 GB/s  48.0%   <- default

    Two findings worth keeping.  Staging the label matrix in shared memory is
    SLOWER: at 185 KB it already lives in L2, so the per-tile __syncthreads costs
    more than the traffic it saves.  And the single biggest win was not a memory
    optimisation at all -- it was making B a compile-time literal so the inner
    popcount loop unrolls.  A runtime trip count cost 1.53x.
    """
    if device == "auto":
        device = "gpu" if gpu_available() else "cpu"
    if device == "gpu":
        return GPUBackend(rules, kernel=kernel)
    return CPUBackend(rules)
