"""
Fast right-tailed Fisher p-values for the minP permutation loop.

Measured motivation
-------------------
On PJM (n=46,324, 75,729 rules) one permutation costs 1.802 s, of which
  popcount   0.069 s   (4%)
  scipy.sf   1.733 s   (96%)
So the bitset work was never the bottleneck; the hypergeometric tail is.

Two ideas, both admissible
--------------------------
L3  Precompute log-factorials once.  Every term of the tail then costs a few
    adds, and the terms are generated by a recurrence so each extra term is a
    single multiply:
        P(A=a+1)/P(A=a) = ((n1-a)(x-a)) / ((a+1)(n-n1-x+a+1))

L5  Early exit.  P(A>=a) >= P(A=a), so the FIRST term alone lower-bounds the
    tail.  For minP we only want the smallest p over all rules, so if that
    lower bound already exceeds the running best, the rule cannot win and the
    tail is never summed.  This is the same admissible-bound argument as
    Tarone, applied one level down.

Correctness note
----------------
A ~ Hypergeom(n, n1, x) has support max(0, x+n1-n) .. min(x, n1).  Starting the
tail recurrence below that lower bound divides by (n - n1 - x + k + 1), which is
zero at k = x+n1-n-1.  Any a at or below the support floor has P(A >= a) = 1, so
we return log p = 0 for those instead of walking into the singularity.
"""

from __future__ import annotations

import numpy as np
from numba import njit, prange


def logfac_table(n: int) -> np.ndarray:
    """L[k] = ln(k!) for k = 0..n, built once."""
    out = np.zeros(n + 1, dtype=np.float64)
    out[1:] = np.cumsum(np.log(np.arange(1, n + 1, dtype=np.float64)))
    return out


@njit(cache=True, inline="always")
def _logpmf(a, n, n1, x, L):
    """ln P(A = a) for A ~ Hypergeom(n, n1, x)."""
    return ((L[n1] - L[a] - L[n1 - a])
            + (L[n - n1] - L[x - a] - L[n - n1 - x + a])
            - (L[n] - L[x] - L[n - x]))


@njit(cache=True)
def minp_scan(a_arr, sup_arr, n, n1, L, best_in):
    """
    Smallest right-tail p over all rules, with the first-term early exit.

    Returns (best_p, n_full_sums) so the prune rate is measurable rather than
    asserted.
    """
    best = best_in
    full = 0
    for i in range(a_arr.shape[0]):
        a = a_arr[i]
        x = sup_arr[i]
        amax = min(x, n1)
        amin = x + n1 - n                      # hypergeometric support lower bound
        if amin < 0:
            amin = 0
        if a > amax:
            continue
        if a <= amin:
            continue                           # P(A >= a) = 1, log p = 0, cannot be the min
        lo = _logpmf(a, n, n1, x, L)          # lower bound on the tail
        if lo > best:                          # cannot beat the running best
            continue
        full += 1
        # accumulate the tail upward by recurrence, in log space via scaling
        s = 1.0
        term = 1.0
        for k in range(a, amax):
            term *= ((n1 - k) * (x - k)) / ((k + 1.0) * (n - n1 - x + k + 1.0))
            s += term
            if term < 1e-18 * s:
                break
        p = lo + np.log(s)
        if p < best:
            best = p
    return best, full


@njit(parallel=True, cache=True)
def minp_null_fast(a_mat, sup_arr, n, n1, L):
    """a_mat: (J, R) counts, one row per permutation.  Returns (J,) log minP."""
    J = a_mat.shape[0]
    out = np.empty(J, dtype=np.float64)
    for j in prange(J):
        b, _ = minp_scan(a_mat[j], sup_arr, n, n1, L, 0.0)
        out[j] = b
    return out


def logp_all_left(a, sup, n, n1, L):
    """
    LEFT tail: log P(A <= a).  Needed for DEPLETION.

    The right tail asks "does this rule hold MORE positives than chance".  A
    reversal is the opposite claim, and testing it with the right tail returns
    a null result for purely mechanical reasons rather than statistical ones.

    Computed by summing DOWNWARD from a with the same recurrence.  Do not use
    1 - exp(right tail): when the right tail is near 1 that cancels catastroph-
    ically and the answer is meaningless.
    """
    out = np.empty(a.shape[0], dtype=np.float64)
    _logp_left(np.asarray(a, np.int64), np.asarray(sup, np.int64), n, n1, L, out)
    return out


@njit(parallel=True, cache=True)
def _logp_left(a_arr, sup_arr, n, n1, L, out):
    for i in prange(a_arr.shape[0]):
        a = a_arr[i]
        x = sup_arr[i]
        amax = min(x, n1)
        amin = x + n1 - n
        if amin < 0:
            amin = 0
        if a >= amax:
            out[i] = 0.0                       # P(A <= amax) = 1
            continue
        if a < amin:
            out[i] = -np.inf                   # impossible
            continue
        lo = _logpmf(a, n, n1, x, L)
        s = 1.0
        term = 1.0
        for k in range(a, amin, -1):           # walk down to the support floor
            term *= (k * (n - n1 - x + k)) / ((n1 - k + 1.0) * (x - k + 1.0))
            s += term
            if term < 1e-18 * s:
                break
        out[i] = lo + np.log(s)


def logp_all(a, sup, n, n1, L):
    """Full RIGHT tail P(A >= a) for every rule -- the enrichment test."""
    out = np.empty(a.shape[0], dtype=np.float64)
    _logp_all(a, sup, n, n1, L, out)
    return out


@njit(parallel=True, cache=True)
def _logp_all(a_arr, sup_arr, n, n1, L, out):
    for i in prange(a_arr.shape[0]):
        a = a_arr[i]
        x = sup_arr[i]
        amax = min(x, n1)
        amin = x + n1 - n
        if amin < 0:
            amin = 0
        if a > amax or a <= amin:
            out[i] = 0.0                       # P(A >= a) = 1 outside/below support
            continue
        lo = _logpmf(a, n, n1, x, L)
        s = 1.0
        term = 1.0
        for k in range(a, amax):
            term *= ((n1 - k) * (x - k)) / ((k + 1.0) * (n - n1 - x + k + 1.0))
            s += term
            if term < 1e-18 * s:
                break
        out[i] = lo + np.log(s)
